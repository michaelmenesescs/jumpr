// TestLabW1AlertToSilence runs SPEC W1 at package level with the alert as the
// entry point: alert data → resolved hosts → investigation → a silence created
// through the action bus and then expired, with both actions recorded and no
// secret in the record.
func TestLabW1AlertToSilence(t *testing.T) {
	stack := loadLabStack(t)
	cookie := labCookie(t)
	labtest.Fault(t, labFault)

	am := stack.amClient(t)
	alert := labWaitForHaproxyAlert(t, am)
	hosts := HostsFromLabels(alert.Labels, stack.inventory(t), nil)
	if len(hosts) == 0 {
		t.Fatalf("HostsFromLabels(%v) resolved no host", alert.Labels)
	}

	red, err := redact.New(nil)
	if err != nil {
		t.Fatalf("lab: redactor: %v", err)
	}
	log := investigation.NewLog(t.TempDir(), red, time.Now)
	now := time.Now()
	meta, err := log.Open(
		"lab W1 "+alert.Labels["alertname"],
		resource.TimeWindow{From: now.Add(-30 * time.Minute), ToNow: true, Label: "-30m"},
		hosts,
		[]string{alert.Labels["alertname"]},
	)
	if err != nil {
		t.Fatalf("lab: open the investigation: %v", err)
	}
	if len(meta.Targets) != len(hosts) {
		t.Fatalf("investigation targets = %v, want %v", meta.Targets, hosts)
	}

	planner := NewAlertmanagerPlanner(AlertmanagerPlannerOptions{
		Servers: []AlertmanagerServer{{Name: stack.am.Name, Client: am}},
		Creator: "jumper-lab",
		Now:     time.Now,
	})
	busy := bus.New(bus.Options{Recorder: log, Redact: red, Now: time.Now})
	if err := busy.Register("alertmanager", planner); err != nil {
		t.Fatalf("lab: register the silence planner: %v", err)
	}

	ctx, cancel := context.WithTimeout(context.Background(), 4*time.Minute)
	defer cancel()

	// Silence the alert through the bus: propose, confirm one target, run.
	comment := "jumper lab W1 " + meta.ID
	create := action.Request{
		SpecID: SpecSilenceCreate,
		Targets: []action.Target{{
			Ref: resource.Ref{
				Backend:   alertmanagerName,
				Kind:      KindAlert,
				Namespace: stack.am.Name,
				Name:      alertRefName(alert),
			},
			Labels: alert.Labels,
		}},
		Params: map[string]string{ParamDuration: "5m", ParamComment: comment},
		Actor:  action.Human,
	}
	proposal, err := busy.Propose(ctx, create)
	if err != nil {
		t.Fatalf("lab: propose silence: %v", err)
	}
	if proposal.Denied != nil {
		t.Fatalf("lab: the default policy denied the silence: %s", proposal.Denied.Reason)
	}
	run, err := busy.Execute(ctx, proposal, bus.Confirmation{ProposalID: proposal.ID})
	if err != nil {
		t.Fatalf("lab: execute silence: %v", err)
	}
	if s := labAwaitRun(t, run); s.OK != 1 || s.Failed != 0 {
		t.Fatalf("lab: silence rollout = ok %d failed %d, want ok 1", s.OK, s.Failed)
	}

	sil := labFindSilence(t, am, comment)
	if state := sil.State(time.Now()); state != SilenceActive {
		t.Fatalf("silence %s state = %s, want %s", sil.ID, state, SilenceActive)
	}

	// Expire it through the bus, as the UI does from the silences list.
	expire := action.Request{
		SpecID: SpecSilenceExpire,
		Targets: []action.Target{{
			Ref: resource.Ref{
				Backend:   alertmanagerName,
				Kind:      KindSilence,
				Namespace: stack.am.Name,
				Name:      sil.ID,
			},
		}},
		Actor: action.Human,
	}
	expireProposal, err := busy.Propose(ctx, expire)
	if err != nil {
		t.Fatalf("lab: propose expire: %v", err)
	}
	if expireProposal.Denied != nil {
		t.Fatalf("lab: the default policy denied the expire: %s", expireProposal.Denied.Reason)
	}
	expireRun, err := busy.Execute(ctx, expireProposal, bus.Confirmation{ProposalID: expireProposal.ID})
	if err != nil {
		t.Fatalf("lab: execute expire: %v", err)
	}
	if s := labAwaitRun(t, expireRun); s.OK != 1 || s.Failed != 0 {
		t.Fatalf("lab: expire rollout = ok %d failed %d, want ok 1", s.OK, s.Failed)
	}
	labWaitSilenceGone(t, am, sil.ID)

	// The record holds both actions and never a credential.
	data, err := os.ReadFile(meta.Path)
	if err != nil {
		t.Fatalf("lab: read the investigation: %v", err)
	}
	text := string(data)
	if n := strings.Count(text, "**action**"); n != 2 {
		t.Fatalf("investigation records %d action bullets, want 2:\n%s", n, text)
	}
	if !strings.Contains(text, "silence") {
		t.Fatalf("investigation does not mention the silence:\n%s", text)
	}
	if cookie != "" && strings.Contains(text, cookie) {
		t.Fatalf("the investigation record contains the SSO cookie")
	}
}

// labWaitForHaproxyAlert polls Alertmanager until the fault's alert fires and
// returns it. A failure lists what was firing instead, which is what makes a
// broken lab rule diagnosable.
func labWaitForHaproxyAlert(t *testing.T, am *AlertmanagerClient) AMAlert {
	t.Helper()
	deadline := time.Now().Add(labAlertWait)
	for {
		ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		alerts, err := am.Alerts(ctx)
		cancel()
		if err != nil {
			t.Fatalf("lab: alertmanager alerts: %v", err)
		}
		for _, a := range alerts {
			if labHaproxyAlert(a) {
				return a
			}
		}
		if time.Now().After(deadline) {
			names := make([]string, 0, len(alerts))
			for _, a := range alerts {
				names = append(names, a.Labels["alertname"]+"@"+a.Labels["instance"])
			}
			t.Fatalf("no %s alert after %s; firing: %s", labFault, labAlertWait, strings.Join(names, ", "))
		}
		time.Sleep(labPollStep)
	}
}

// labHaproxyAlert reports whether a is the alert the haproxy-443 fault raises:
// it names the port conflict and names a host the fault touched.
func labHaproxyAlert(a AMAlert) bool {
	if !labFaultHosts[resource.HostID(instanceHost(a.Labels["instance"]))] {
		return false
	}
	words := []string{a.Labels["alertname"]}
	for k, v := range a.Labels {
		if k != "alertname" {
			words = append(words, v)
		}
	}
	for _, v := range a.Annotations {
		words = append(words, v)
	}
	for _, w := range words {
		if strings.Contains(strings.ToLower(w), "haproxy") {
			return true
		}
	}
	return false
}

// labFindSilence waits for the silence carrying comment to appear and returns
// it. Alertmanager answers a create before its own state settles, so this
// polls.
func labFindSilence(t *testing.T, am *AlertmanagerClient, comment string) AMSilence {
	t.Helper()
	deadline := time.Now().Add(30 * time.Second)
	for {
		ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		silences, err := am.Silences(ctx)
		cancel()
		if err != nil {
			t.Fatalf("lab: alertmanager silences: %v", err)
		}
		for _, s := range silences {
			if s.Comment == comment {
				return s
			}
		}
		if time.Now().After(deadline) {
			t.Fatalf("the created silence (%q) did not appear in alertmanager", comment)
		}
		time.Sleep(time.Second)
	}
}

// labWaitSilenceGone waits for a deleted silence to leave Alertmanager.
func labWaitSilenceGone(t *testing.T, am *AlertmanagerClient, id string) {
	t.Helper()
	deadline := time.Now().Add(30 * time.Second)
	for {
		ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		silences, err := am.Silences(ctx)
		cancel()
		if err != nil {
			t.Fatalf("lab: alertmanager silences: %v", err)
		}
		found := false
		for _, s := range silences {
			if s.ID == id {
				found = true
				break
			}
		}
		if !found {
			return
		}
		if time.Now().After(deadline) {
			t.Fatalf("silence %s is still in alertmanager after the expire", id)
		}
		time.Sleep(time.Second)
	}
}

// labAwaitRun drains a rollout and returns its summary.
func labAwaitRun(t *testing.T, run bus.Run) bus.Summary {
	t.Helper()
	if run == nil {
		t.Fatalf("lab: nil run")
	}
	timeout := time.After(4 * time.Minute)
	for {
		select {
		case ev, ok := <-run.Events():
			if !ok {
				t.Fatalf("lab: the rollout closed without a summary")
			}
			if ev.Result != nil && ev.Result.Err != nil {
				t.Logf("lab: step failed: %v", ev.Result.Err)
			}
			if ev.Summary != nil {
				return *ev.Summary
			}
		case <-timeout:
			t.Fatalf("lab: the rollout did not finish in 4m")
		}
	}
}

// labListAll drains one backend List into a slice.
func labListAll(t *testing.T, b backend.Backend, q resource.Query) []resource.Resource {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 45*time.Second)
	defer cancel()
	ch, err := b.List(ctx, q)
	if err != nil {
		t.Fatalf("lab: list %s: %v", q.Kind, err)
	}
	var out []resource.Resource
	for res := range ch {
		if res.Err != nil {
			t.Fatalf("lab: list %s: %v", q.Kind, res.Err)
		}
		out = append(out, res.Items...)
	}
	return out
}
