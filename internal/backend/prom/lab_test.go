// inventory loads the lab inventory from Prometheus targets, which is how an
// alert's instance label resolves to a host (task 103).
func (s *labStack) inventory(t *testing.T) inventory.Inventory {
	t.Helper()
	src := NewSource(s.prom.Name, s.promClient(t))
	inv := inventory.New([]inventory.Source{src}, nil, "", time.Now)
	ctx, cancel := context.WithTimeout(context.Background(), 45*time.Second)
	defer cancel()
	if failed := inv.Refresh(ctx); failed[src.Name()] != nil {
		t.Fatalf("lab: prometheus inventory source: %v", failed[src.Name()])
	}
	if len(inv.Hosts()) == 0 {
		t.Fatalf("lab: the prometheus inventory source returned no hosts")
	}
	return inv
}

// rawClient is a plain HTTP client with the profile's TLS settings, no auth and
// no redirect following: what a manual `curl -k` would do.
func (s *labStack) rawClient(t *testing.T) *http.Client {
	t.Helper()
	p := s.profile(t)
	tr := &http.Transport{
		TLSClientConfig: &tls.Config{
			MinVersion:         tls.VersionTLS12,
			ServerName:         p.TLS.ServerName,
			InsecureSkipVerify: p.TLS.InsecureSkipVerify,
		},
	}
	t.Cleanup(tr.CloseIdleConnections)
	return &http.Client{
		Transport: tr,
		Timeout:   20 * time.Second,
		CheckRedirect: func(*http.Request, []*http.Request) error {
			return http.ErrUseLastResponse
		},
	}
}

// labCookie returns the cookie the helper should return, skipping when the
// developer did not export one: without it the stack cannot be authenticated at
// all, which is the same as the stack being absent for these tests.
func labCookie(t *testing.T) string {
	t.Helper()
	cookie := strings.TrimSpace(os.Getenv(labCookieVar))
	if cookie == "" {
		t.Skipf("%s: export %s to the cookie the lab mock SSO proxy hands out", labSkip, labCookieVar)
	}
	return cookie
}

// TestLabSSOProfileRedirectsWithoutCookie proves the lab proxy sends an
// unauthenticated request to its login page and that the profile classifies the
// resulting session failure as errs.Auth rather than a parse or remote error.
func TestLabSSOProfileRedirectsWithoutCookie(t *testing.T) {
	stack := loadLabStack(t)
	t.Setenv(labCookieVar, "expired-lab-session")

	// A bare request with no cookie is redirected, not served.
	req, err := http.NewRequestWithContext(context.Background(), http.MethodGet, stack.prom.URL, nil)
	if err != nil {
		t.Fatalf("lab: request: %v", err)
	}
	resp, err := stack.rawClient(t).Do(req)
	if err != nil {
		t.Fatalf("GET %s without a cookie: %v", stack.prom.URL, err)
	}
	defer resp.Body.Close()
	_, _ = io.Copy(io.Discard, io.LimitReader(resp.Body, 1<<12))
	if resp.StatusCode < 300 || resp.StatusCode >= 400 {
		t.Fatalf("GET %s without a cookie: status %d, want a redirect to the login page", stack.prom.URL, resp.StatusCode)
	}
	if loc := resp.Header.Get("Location"); !strings.Contains(strings.ToLower(loc), "login") {
		t.Fatalf("redirect Location = %q, want a login page", loc)
	}

	// Through the profile the same stale cookie ends as an Auth error: the
	// client runs the helper, gets the same stale value back, and stops.
	ctx, cancel := context.WithTimeout(context.Background(), 45*time.Second)
	defer cancel()
	if _, err := stack.promClient(t).Targets(ctx); err == nil {
		t.Fatalf("targets with a stale cookie succeeded; the proxy accepted it")
	} else if kind := errs.KindOf(err); kind != errs.Auth {
		t.Fatalf("targets with a stale cookie: kind = %q, want auth: %v", kind, err)
	}
}

