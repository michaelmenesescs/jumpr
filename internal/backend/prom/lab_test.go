// TestLabSSOHelperRefreshAfterInvalidation proves a client that already holds
// credentials recovers when the proxy invalidates the cookie: the 302 makes the
// client drop its cache, re-run the helper once and retry.
func TestLabSSOHelperRefreshAfterInvalidation(t *testing.T) {
	stack := loadLabStack(t)
	labCookie(t)

	pc := stack.promClient(t)
	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	defer cancel()
	if _, err := pc.Targets(ctx); err != nil {
		t.Fatalf("prometheus targets before invalidation: %v", err)
	}

	renewed, err := stack.invalidateSession(t, ctx)
	if errors.Is(err, errNoControlEndpoint) {
		t.Skipf("%s: the mock SSO proxy has no %s control endpoint", labSkip, labInvalidatePath)
	}
	if err != nil {
		t.Fatalf("lab: invalidate the session: %v", err)
	}
	// The helper reads the cookie when it runs; the refreshed run must see the
	// renewed value, not the stale one it cached.
	t.Setenv(labCookieVar, renewed)

	if _, err := pc.Targets(ctx); err != nil {
		t.Fatalf("prometheus targets after the proxy invalidated the cookie: the helper did not refresh: %v", err)
	}
}

// invalidateSession asks the mock proxy to invalidate the current cookie and
// returns the renewed one.
func (s *labStack) invalidateSession(t *testing.T, ctx context.Context) (string, error) {
	t.Helper()
	target := strings.TrimRight(s.prom.URL, "/") + labInvalidatePath
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, target, nil)
	if err != nil {
		return "", err
	}
	resp, err := s.rawClient(t).Do(req)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()
	body, _ := io.ReadAll(io.LimitReader(resp.Body, 4<<10))
	if resp.StatusCode == http.StatusNotFound || resp.StatusCode == http.StatusMethodNotAllowed {
		return "", errNoControlEndpoint
	}
	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		return "", fmt.Errorf("%s: status %d %s: %s", labInvalidatePath, resp.StatusCode,
			http.StatusText(resp.StatusCode), strings.TrimSpace(string(body)))
	}
	var doc struct {
		Cookie string `json:"cookie"`
	}
	if err := json.Unmarshal(body, &doc); err != nil || strings.TrimSpace(doc.Cookie) == "" {
		return "", fmt.Errorf("%s: no cookie in the answer", labInvalidatePath)
	}
	return strings.TrimSpace(doc.Cookie), nil
}

// TestLabAlertsContainHaproxyFault proves the `:alerts` data contains the alert
// the lab's haproxy-443 fault fires.
func TestLabAlertsContainHaproxyFault(t *testing.T) {
	stack := loadLabStack(t)
	labCookie(t)
	labtest.Fault(t, labFault)

	am := stack.amClient(t)
	alert := labWaitForHaproxyAlert(t, am)

	amb := NewAlertmanager(AlertmanagerOptions{
		Servers: []AlertmanagerServer{{Name: stack.am.Name, Client: am}},
	})
	rows := labListAll(t, amb, resource.Query{Kind: KindAlert})
	name := alert.Labels["alertname"]
	var found *resource.Resource
	for i := range rows {
		if rows[i].Ref.Kind != KindAlert {
			t.Fatalf(":alerts row kind = %q, want %q", rows[i].Ref.Kind, KindAlert)
		}
		if rows[i].Labels["alertname"] == name && rows[i].Str("alert") == name {
			found = &rows[i]
			break
		}
	}
	if found == nil {
		t.Fatalf("the :alerts rows (%d) do not contain the firing alert %q", len(rows), name)
	}
	if state := found.Str("state"); state == AlertSilenced || state == AlertInhibited {
		t.Fatalf("alert %q is %s; the haproxy fault alert must be firing", name, state)
	}
}

