const (
	// labSkip is the message every test in this file uses when the stack is
	// not up (task 104, requirement 1).
	labSkip = "lab observability stack not running"
	// labProfile is the connection profile both lab servers use.
	labProfile = "lab-sso"
	// labCookieVar is what examples/auth-helper-cookie reads.
	labCookieVar = "JUMPER_AUTH_COOKIE"
	// labInvalidatePath is the mock proxy's lab-only session control.
	labInvalidatePath = "/__lab/sso/invalidate"
	// labFault is the fault whose alert these tests follow.
	labFault = "haproxy-443"
	// labAlertWait is how long an injected fault may take to reach
	// Alertmanager: one scrape plus the rule's `for:` and a little slack.
	labAlertWait = 4 * time.Minute
	// labPollStep is the alert polling interval.
	labPollStep = 5 * time.Second
)

// labDomain is the suffix of every lab host (SPEC §22).
const labDomain = ".lab.example.internal"

// labFaultHosts are the hosts `haproxy-443` touches: web-01 and web-02.
var labFaultHosts = map[resource.HostID]bool{
	resource.HostID("web-01" + labDomain): true,
	resource.HostID("web-02" + labDomain): true,
}

// errNoControlEndpoint reports a proxy without the session control endpoint.
var errNoControlEndpoint = errors.New("no session control endpoint")

// labStack is what one test needs from the lab's observability stack.
type labStack struct {
	root     string
	home     string
	profiles map[string]*httpx.Profile
	deps     httpx.Deps
	prom     config.PrometheusConfig
	am       config.AlertmanagerConfig
}

// loadLabStack loads lab/jumper, moves to the repository root (the profile's
// helper path is relative to it) and skips unless the stack is up.
func loadLabStack(t *testing.T) *labStack {
	t.Helper()
	root := labtest.Root(t)
	chdirLab(t, root)

	home, err := os.UserHomeDir()
	if err != nil {
		t.Fatalf("lab: home directory: %v", err)
	}
	cfg, err := config.Load(filepath.Join("lab", "jumper", "config.yaml"), home)
	if err != nil {
		t.Fatalf("lab: config: %v", err)
	}
	if len(cfg.Prometheus) == 0 || len(cfg.Alertmanager) == 0 {
		t.Skipf("%s: lab/jumper/config.yaml configures no prometheus and alertmanager server", labSkip)
	}
	profiles, err := config.LoadConnections(filepath.Join("lab", "jumper", "connections.yaml"), home)
	if err != nil {
		t.Fatalf("lab: connections: %v", err)
	}
	p, ok := profiles[labProfile]
	if !ok || p == nil {
		t.Skipf("%s: lab/jumper/connections.yaml has no %q profile", labSkip, labProfile)
	}
	if p.Auth.Helper == nil || len(p.Auth.Helper.Command) == 0 {
		t.Fatalf("lab: profile %q has no auth helper", labProfile)
	}

	// lab/ssh_config is generated by `sitrep-lab up`; without it the lab (and
	// therefore its observability stack) is down.
	if _, err := os.Stat(filepath.Join("lab", "ssh_config")); err != nil {
		t.Skipf("%s: the lab is down (lab/ssh_config missing); run: go run ./cmd/sitrep-lab up", labSkip)
	}
	// The helper is built by hand (task 104): a missing binary means the stack
	// cannot authenticate, not that jumper is broken.
	helper := p.Auth.Helper.Command[0]
	if !filepath.IsAbs(helper) {
		helper = filepath.Join(root, helper)
	}
	if _, err := os.Stat(helper); err != nil {
		t.Skipf("%s: build the auth helper first: go build -o lab/.keys/auth-helper ./examples/auth-helper-cookie", labSkip)
	}
	for _, raw := range []string{cfg.Prometheus[0].URL, cfg.Alertmanager[0].URL} {
		if err := labReachable(raw); err != nil {
			t.Skipf("%s: %s is not reachable: %v", labSkip, raw, err)
		}
	}

	red, err := redact.New(nil)
	if err != nil {
		t.Fatalf("lab: redactor: %v", err)
	}
	return &labStack{
		root:     root,
		home:     home,
		profiles: profiles,
		deps:     httpx.Deps{Env: labEnv(), Home: home, Redactor: red},
		prom:     cfg.Prometheus[0],
		am:       cfg.Alertmanager[0],
	}
}

// chdirLab moves to dir for the rest of the test and restores the old
// directory in cleanup. The profile's helper path is relative to the root.
func chdirLab(t *testing.T, dir string) {
	t.Helper()
	old, err := os.Getwd()
	if err != nil {
		t.Fatalf("lab: %v", err)
	}
	if old == dir {
		return
	}
	if err := os.Chdir(dir); err != nil {
		t.Fatalf("lab: chdir %s: %v", dir, err)
	}
	t.Cleanup(func() { _ = os.Chdir(old) })
}

// labEnv returns the process environment as a map, without touching it.
func labEnv() map[string]string {
	env := map[string]string{}
	for _, kv := range os.Environ() {
		if k, v, ok := strings.Cut(kv, "="); ok {
			env[k] = v
		}
	}
	return env
}

// labReachable reports whether the URL's host accepts a TCP connection. It is
// the cheapest honest answer to "is the stack up"; the proxy itself answers
// nothing without a cookie.
func labReachable(raw string) error {
	u, err := url.Parse(strings.TrimSpace(raw))
	if err != nil {
		return err
	}
	if u.Hostname() == "" {
		return fmt.Errorf("%q has no host", raw)
	}
	addr := u.Host
	if u.Port() == "" {
		port := "80"
		if u.Scheme == "https" {
			port = "443"
		}
		addr = net.JoinHostPort(u.Hostname(), port)
	}
	conn, err := net.DialTimeout("tcp", addr, 3*time.Second)
	if err != nil {
		return err
	}
	return conn.Close()
}

// profile returns a copy of the lab-sso profile: the helper cache lives in the
// client, so every client the tests build starts empty.
func (s *labStack) profile(t *testing.T) *httpx.Profile {
	t.Helper()
	p, ok := s.profiles[labProfile]
	if !ok || p == nil {
		t.Fatalf("lab: profile %q disappeared", labProfile)
	}
	cp := *p
	return &cp
}

